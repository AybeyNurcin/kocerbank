    V_ACILIS_TARIHI := SYSDATE;
    LOOP
        SELECT KB_HESAPBILGILERI_SEQ.NEXTVAL INTO V_ID FROM DUAL;
        V_HESAP_NO := LPAD(REGEXP_SUBSTR(V_SUBE_KODU, '[0-9]+$'), 4, '0')
                      || TO_CHAR(V_ACILIS_TARIHI, 'DDMMYYYY')
                      || LPAD(MOD(V_ID, 10000), 4, '0');
        SELECT COUNT(*) INTO V_ADET FROM KB_HESAPBILGILERI WHERE HESAPNO = V_HESAP_NO;
        EXIT WHEN V_ADET = 0;
    END LOOP;

