-- Kontrol: Eklenen 50 hesap ve sahiplerinin aktif hesap sayısı
SELECT
    M.ID AS MUSTERI_ID,
    M.EPOSTA,
    COUNT(H.ID) AS TOPLAM_HESAP_SAYISI,
    SUM(CASE WHEN H.HESAPDURUMKODU = 1 THEN 1 ELSE 0 END) AS AKTIF_HESAP_SAYISI
FROM KB_MUSTERIBILGILERI M
JOIN KB_HESAPBILGILERI H ON H.MUSTERIBILGILERIID = M.ID
WHERE M.ID IN (
    SELECT MUSTERIBILGILERIID FROM KB_HESAPBILGILERI
    WHERE HESAPADI IN ('Virman Birikim Hesabım', 'Virman İkinci Hesabım')
)
GROUP BY M.ID, M.EPOSTA
ORDER BY M.EPOSTA;

-- Hesap numarası ve IBAN kontrolü
SELECT
    H.ID, M.EPOSTA, H.HESAPNO,
    SUBSTR(H.HESAPNO, 1, 4) AS SUBE_HANELERI,
    SUBSTR(H.HESAPNO, 5, 8) AS TARIH_HANELERI,
    TO_CHAR(H.HESAPACILISTARIHI, 'DDMMYYYY') AS HESAP_ACILIS_TARIHI,
    SUBSTR(H.HESAPNO, 13, 4) AS SEQUENCE_HANELERI,
    H.IBAN, LENGTH(H.HESAPNO) AS HESAPNO_UZUNLUK, LENGTH(H.IBAN) AS IBAN_UZUNLUK
FROM KB_HESAPBILGILERI H
JOIN KB_MUSTERIBILGILERI M ON M.ID = H.MUSTERIBILGILERIID
WHERE H.HESAPADI IN ('Virman Birikim Hesabım', 'Virman İkinci Hesabım')
ORDER BY H.ID;

