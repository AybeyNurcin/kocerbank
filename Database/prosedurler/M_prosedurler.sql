CREATE OR REPLACE PROCEDURE
KB_MUSTERI_ILETISIM_TAM_GUNCELLE
(
    P_MUSTERIBILGILERIID
        IN KB_MUSTERIBILGILERI.ID%TYPE,

    P_TELEFONNO
        IN KB_MUSTERIBILGILERI.TELEFONNO%TYPE,

    P_EPOSTA
        IN KB_MUSTERIBILGILERI.EPOSTA%TYPE,

    P_EVTELEFON
        IN KB_MUSTERIILETISIM.EVTELEFON%TYPE,

    P_ISTELEFON
        IN KB_MUSTERIILETISIM.ISTELEFON%TYPE,

    P_EVADRES
        IN KB_MUSTERIILETISIM.EVADRES%TYPE,

    P_ISADRES
        IN KB_MUSTERIILETISIM.ISADRES%TYPE
)
AS
BEGIN

    /* MÜŞTERİ TABLOSUNDAKİ
       TELEFON VE E-POSTA */

    UPDATE KB_MUSTERIBILGILERI
    SET
        TELEFONNO = P_TELEFONNO,
        EPOSTA = P_EPOSTA
    WHERE
        ID = P_MUSTERIBILGILERIID;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20001,
            'Müşteri bulunamadı.'
        );
    END IF;


    /* İLETİŞİM TABLOSUNDAKİ
       BÜTÜN İLETİŞİM BİLGİLERİ */

    UPDATE KB_MUSTERIILETISIM
    SET
        TELEFONNO = P_TELEFONNO,
        EPOSTA = P_EPOSTA,
        EVTELEFON = P_EVTELEFON,
        ISTELEFON = P_ISTELEFON,
        EVADRES = P_EVADRES,
        ISADRES = P_ISADRES
    WHERE
        MUSTERIBILGILERIID =
            P_MUSTERIBILGILERIID;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20002,
            'Müşteri iletişim kaydı bulunamadı.'
        );
    END IF;

END KB_MUSTERI_ILETISIM_TAM_GUNCELLE;
