CREATE OR REPLACE PROCEDURE KB_HESAPDASHBOARD
(
    P_BASLANGICTARIHI IN  DATE DEFAULT NULL,
    P_BITISTARIHI     IN  DATE DEFAULT NULL,
    P_SONUC           OUT SYS_REFCURSOR
)
AS
BEGIN
    OPEN P_SONUC FOR
    SELECT COUNT(*) AS HESAP_SAYISI,
           SUM(CASE WHEN HESAPDURUMKODU = 1 THEN 1 ELSE 0 END) AS AKTIFSAYI,
           SUM(CASE WHEN HESAPDURUMKODU = 2 THEN 1 ELSE 0 END) AS PASIFSAYI,
           SUM(CASE WHEN DOVIZCINSI = 1 THEN 1 ELSE 0 END) AS TLSAYI,
           SUM(CASE WHEN DOVIZCINSI = 2 THEN 1 ELSE 0 END) AS USDSAYI,
           SUM(CASE WHEN DOVIZCINSI = 3 THEN 1 ELSE 0 END) AS EURSAYI
    FROM KB_HESAPBILGILERI
    WHERE (P_BASLANGICTARIHI IS NULL OR TRUNC(HESAPACILISTARIHI) >= TRUNC(P_BASLANGICTARIHI))
      AND (P_BITISTARIHI IS NULL OR TRUNC(HESAPACILISTARIHI) <= TRUNC(P_BITISTARIHI));
END KB_HESAPDASHBOARD;
