CREATE OR REPLACE PROCEDURE KB_PERSONEL_EKLE
(
    P_AD                IN  KB_PERSONEL.AD%TYPE,
    P_SOYAD             IN  KB_PERSONEL.SOYAD%TYPE,
    P_ROL               IN  KB_PERSONEL.ROL%TYPE,
    P_SIFRE             IN  KB_PERSONEL.SIFRE%TYPE,
    P_TCKN              IN  KB_PERSONEL.TCKN%TYPE,
    P_TELEFONNO         IN  KB_PERSONEL.TELEFONNO%TYPE,
    P_ADRES             IN  KB_PERSONEL.ADRES%TYPE,
    P_EPOSTA            IN  KB_PERSONEL.EPOSTA%TYPE,
    P_SUBEKODU          IN  KB_PERSONEL.SUBESUBEKODU%TYPE,
    P_DURUMKODU         IN  KB_PERSONEL.DURUMKODU%TYPE,
    P_RECORDUSER        IN  KB_PERSONEL.RECORDUSER%TYPE,

    P_ID                    OUT KB_PERSONEL.ID%TYPE,
    P_SICIL                 OUT KB_PERSONEL.SICIL%TYPE,
    P_KAYITOLUSTURMATARIHI  OUT KB_PERSONEL.KAYITOLUSTURMATARIHI%TYPE
)
AS
    V_RECORDUSER KB_PERSONEL.RECORDUSER%TYPE;
    V_RECORDDATE KB_PERSONEL.RECORDDATE%TYPE;
BEGIN
    KB_AUDIT_BILGI_HAZIRLA
    (
        P_RECORDUSER       => P_RECORDUSER,
        P_DUZENLENMIS_USER => V_RECORDUSER,
        P_RECORDDATE       => V_RECORDDATE
    );

    INSERT INTO KB_PERSONEL
    (
        AD,
        SOYAD,
        ROL,
        SIFRE,
        TCKN,
        TELEFONNO,
        ADRES,
        EPOSTA,
        SUBESUBEKODU,
        DURUMKODU,
        RECORDUSER,
        RECORDDATE
    )
    VALUES
    (
        P_AD,
        P_SOYAD,
        P_ROL,
        P_SIFRE,
        P_TCKN,
        P_TELEFONNO,
        P_ADRES,
        P_EPOSTA,
        P_SUBEKODU,
        P_DURUMKODU,
        V_RECORDUSER,
        V_RECORDDATE
    )
    RETURNING ID, SICIL, KAYITOLUSTURMATARIHI INTO P_ID, P_SICIL, P_KAYITOLUSTURMATARIHI;
END ;
/



